import { createHash, randomUUID } from 'node:crypto'
import { join } from 'node:path'
import { accents, type SavedTab } from '../../shared/model.js'
import { webUrl } from '../../shared/navigation.js'
import type { Database } from './database.js'
import { exportedLinks, mergeImported, readChromium, readImportFile, type Entry, type Link, type Source } from './importData.js'

type ImportedProfile = {
  key: string; name: string; accent?: string; theme?: 'system' | 'light' | 'dark'; favorites: Link[]; pinned: Link[]; tabs: Link[]
  bookmarks: Link[]; history: Entry[]; notes: string[]
}

export async function chromiumProfile(source: Source): Promise<ImportedProfile> {
  const [data, preferences] = await Promise.all([
    readChromium(source.path, true),
    readImportFile(join(source.path, 'Preferences')).then(contents => JSON.parse(contents) as {
      browser?: { theme?: { user_color?: unknown; user_color2?: unknown; color_scheme?: unknown; color_scheme2?: unknown } }
      autogenerated?: { theme?: { color?: unknown } }
      pinned_tabs?: unknown
    }).catch(() => null),
  ])
  const color = [
    preferences?.browser?.theme?.user_color2, preferences?.browser?.theme?.user_color, preferences?.autogenerated?.theme?.color,
  ].find((value): value is number => typeof value === 'number' && Number.isInteger(value) &&
    value >= -2147483648 && value <= 0xffffffff && (value >>> 24) === 255)
  const storedPins: unknown[] = Array.isArray(preferences?.pinned_tabs) ? preferences.pinned_tabs : []
  const scheme = preferences?.browser?.theme?.color_scheme2 ?? preferences?.browser?.theme?.color_scheme
  const pinned = storedPins.flatMap(item => {
    if (!item || typeof item !== 'object' || !('url' in item) || typeof item.url !== 'string') return []
    const url = webUrl(item.url)
    if (!url || url.length > 8192) return []
    const title = 'title' in item && typeof item.title === 'string' ? item.title.trim().slice(0, 512) : ''
    return [{ url, title: title || new URL(url).hostname, folder: '' }]
  })
  return {
    key: source.id, name: source.label, accent: color === undefined ? undefined : '#' + (color & 0xffffff).toString(16).padStart(6, '0'),
    theme: scheme === 0 ? 'system' : scheme === 1 ? 'light' : scheme === 2 ? 'dark' : undefined,
    favorites: data.toolbar, pinned, tabs: [], bookmarks: data.links, history: data.history, notes: data.notes,
  }
}

const cleanHeading = (text: string) => text.replace(/^[^\p{L}\p{N}]+/u, '').trim()
const containerHeading = /^(?:arc|dia)(?: browser)?(?: data| tabs| profile)? export\b|^(?:profiles|spaces)$/i
const sectionPatterns = [
  ['favorites', /^favou?rites(?:\s*\(\d+\))?$/i],
  ['pinned', /^(?:pinned(?: tabs)?|tab groups|groups)(?:\s*\(\d+\))?$/i],
  ['tabs', /^(?:today(?: tabs)?|open tabs|tabs|unpinned(?: tabs)?)(?:\s*\(\d+\))?$/i],
  ['bookmarks', /^bookmarks(?:\s*\(\d+\))?$/i],
] as const

function outline(headings: string[], fallback: string) {
  const meaningful = headings.map(cleanHeading).filter(heading => heading && !containerHeading.test(heading))
  const section = meaningful.findIndex(heading => sectionPatterns.some(([, pattern]) => pattern.test(heading)))
  const containers = section === -1 ? meaningful : meaningful.slice(0, section)
  const explicit = containers.findIndex(name => /^profile\s*[:–-]/i.test(name))
  const name = (containers[explicit < 0 ? 0 : explicit] || fallback).replace(/^(?:profile|space)\s*[:–-]\s*/i, '').trim().slice(0, 64) || fallback
  const kind = sectionPatterns.find(([, pattern]) => pattern.test(meaningful[section] ?? ''))?.[0] ?? 'tabs'
  const folders = section === -1 ? containers.slice(1) : [...containers.slice((explicit < 0 ? 0 : explicit) + 1), ...meaningful.slice(section + 1)]
  return { name, kind, folder: folders.join(' › ').slice(0, 120) }
}

export function markdownProfiles(contents: string, browser: string): ImportedProfile[] {
  const profiles = new Map<string, ImportedProfile>()
  const fallback = browser + ' import'
  const get = (name: string) => {
    const found = profiles.get(name)
    if (found) return found
    const profile: ImportedProfile = {
      key: createHash('sha256').update(JSON.stringify(['markdown', browser, name])).digest('hex'), name,
      favorites: [], pinned: [], tabs: [], bookmarks: [], history: [], notes: [],
    }
    profiles.set(name, profile)
    return profile
  }
  for (const link of exportedLinks(contents, true)) {
    const { name, kind, folder } = outline(link.folder.split(' › '), fallback)
    get(name)[kind].push({ ...link, folder })
  }
  const headings: { level: number; title: string }[] = []
  for (const line of contents.split(/\r?\n/)) {
    const head = /^(#{1,6})\s+(.+)$/.exec(line)
    if (head) {
      while ((headings.at(-1)?.level ?? 0) >= head[1].length) headings.pop()
      headings.push({ level: head[1].length, title: head[2].trim() })
      if (/^(?:profile|space)\s*[:–-]/i.test(cleanHeading(head[2]))) {
        const { name } = outline(headings.map(item => item.title), fallback)
        get(name)
      }
      continue
    }
    const color = /^\s*(?:[-*]\s*)?(?:\*\*)?(?:theme |accent )?colou?r\s*:\s*(?:\*\*)?\s*(#[a-f\d]{6})\s*$/i.exec(line)
    if (color) {
      const { name } = outline(headings.map(item => item.title), fallback)
      const profile = profiles.get(name)
      if (profile) profile.accent = color[1].toLowerCase()
    }
  }
  return [...profiles.values()]
}

export function saveBrowserProfiles(db: Database, sources: ImportedProfile[]) {
  const results = { profiles: [] as { id: string; name: string }[], bookmarks: 0, visits: 0, favorites: 0, pinned: 0, tabs: 0, passwords: 0, notes: [] as string[] }
  const createdTabs: SavedTab[] = []
  db.transaction(() => {
    for (const source of sources) {
      const importKey = 'browser-import:' + source.key
      const savedId = db.get(importKey, '')
      let target = db.one<{ id: string; name: string }>('SELECT id, name FROM workspaces WHERE id = ? AND profileId IS NULL', savedId)
      if (!target) {
        const id = randomUUID()
        const accent = source.accent || accents[results.profiles.length % accents.length]
        let name = source.name
        let suffix = 2
        while (db.one('SELECT id FROM workspaces WHERE name = ? COLLATE NOCASE', name)) {
          name = source.name.slice(0, 56) + ' (' + suffix++ + ')'
        }
        db.addWorkspace(id, name, accent, null, '', false)
        if (source.accent) db.setProfileSetting(id, 'accentColor', accent)
        if (source.theme) db.setProfileSetting(id, 'theme', source.theme)
        db.set(importKey, id)
        target = { id, name }
      }
      results.profiles.push({ id: target.id, name: target.name })
      const profile = target.id
      const merged = mergeImported(db, profile, source.bookmarks, source.history)
      results.bookmarks += merged.bookmarks
      results.visits += merged.visits
      let favoritePosition = db.one<{ next: number }>('SELECT COALESCE(MAX(position), -1) + 1 AS next FROM favorites WHERE profileId = ?', profile)!.next
      for (const { url, title } of source.favorites) {
        const added = db.run(`INSERT INTO favorites (profileId, id, url, title, position) VALUES (?, ?, ?, ?, ?)
          ON CONFLICT(profileId, url) DO NOTHING`, profile, randomUUID(), url, title, favoritePosition)
        if (added.changes) { results.favorites++; favoritePosition++ }
      }
      let position = db.one<{ next: number }>('SELECT COALESCE(MAX(position), -1) + 1 AS next FROM tabs WHERE workspaceId = ?', profile)!.next
      const groups = new Map<string, string>()
      for (const [links, pinned] of [[source.pinned, 1], [source.tabs, 0]] as const) {
        for (const { url, title, folder } of links) {
          if (db.one('SELECT id FROM tabs WHERE workspaceId = ? AND url = ?', profile, url)) continue
          let groupId: string | null = null
          let key = ''
          for (const name of pinned && folder ? folder.split(' › ') : []) {
            key += '/' + name
            let group: string | undefined = groups.get(key) ?? db.one<{ id: string }>('SELECT id FROM tab_groups WHERE workspaceId = ? AND name = ? AND parentId IS ?', profile, name, groupId)?.id
            if (!group) {
              group = randomUUID()
              db.run('INSERT INTO tab_groups (id, workspaceId, name, parentId) VALUES (?, ?, ?, ?)', group, profile, name, groupId)
            }
            groups.set(key, group)
            groupId = group
          }
          const tab: SavedTab = { id: randomUUID(), workspaceId: profile, url, title, favicon: null, pinned, groupId, position: position++, lastUsed: Date.now() }
          db.run('INSERT INTO tabs (id, workspaceId, url, title, favicon, pinned, groupId, position, lastUsed) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)',
            tab.id, profile, url, title, null, pinned, groupId, tab.position, tab.lastUsed)
          createdTabs.push(tab)
          if (pinned) results.pinned++
          else results.tabs++
        }
      }
      results.notes.push(...source.notes.map(note => source.name + ' · ' + note))
    }
  })
  return { results, createdTabs }
}
